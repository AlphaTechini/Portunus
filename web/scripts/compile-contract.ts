// Compiles contracts/PortunusSettlement.sol and writes ABI + bytecode into
// src/lib/shared/tempo/settlementAbi.ts (generated; committed so the app never needs solc at runtime).
//   npm run compile:contract
import { writeFileSync } from 'node:fs';
import { compileSettlement } from './lib/solc';

const OUT = new URL('../src/lib/shared/tempo/settlementAbi.ts', import.meta.url);

const c = compileSettlement();
const body = `// GENERATED by web/scripts/compile-contract.ts from contracts/PortunusSettlement.sol. Do not edit.
// solc ${c.solcVersion}, evmVersion ${c.evmVersion}, optimizer enabled (200 runs).
/* eslint-disable */

// prettier-ignore
export const settlementAbi = ${JSON.stringify(c.abi, null, '\t')} as const;

// prettier-ignore
export const settlementBytecode = '${c.bytecode}' as const;

export const settlementBuild = {
	solc: '${c.solcVersion}',
	evmVersion: '${c.evmVersion}',
	bytecodeBytes: ${(c.bytecode.length - 2) / 2}
} as const;
`;
writeFileSync(OUT, body);
console.log(
	`compiled PortunusSettlement (${c.evmVersion}), ${(c.bytecode.length - 2) / 2} bytes -> src/lib/shared/tempo/settlementAbi.ts`
);
